    public static function locale(): string
    {
        $locale = (string)($_SESSION['locale'] ?? 'pt-BR');
        return isset(self::$messages[$locale]) ? $locale : 'pt-BR';
    }

    public static function t(string $key, array $replace = [], ?string $locale = null): string
    {
        $locale = $locale ?? self::locale();
        $catalog = self::$messages[$locale] ?? self::$messages['pt-BR'];
        $text = $catalog[$key] ?? (self::$messages['pt-BR'][$key] ?? $key);
        foreach ($replace as $name => $value) {
            $text = str_replace('{' . $name . '}', (string)$value, $text);
        }
        return $text;
    }
